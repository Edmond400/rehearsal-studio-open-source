import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {dirname} from 'node:path';
const require=createRequire(import.meta.url);
const {build}=require(require.resolve('esbuild',{paths:[dirname(require.resolve('wrangler/package.json'))]}));
const bundle=await build({stdin:{contents:[
 'editing','script-reconcile','deck-replace','draft-merge','draft-client','model','turn-identity'
].map(name=>"export * from './lib/rehearsal/"+name+"';").join('\n'),resolveDir:process.cwd(),loader:'ts'},bundle:true,platform:'node',format:'esm',write:false});
const a=await import('data:text/javascript;base64,'+Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const block=(id,text,memberId='a',extra={})=>({id,paragraphId:id,text,memberId,slideIndex:0,nonspoken:false,paragraphEnd:true,...extra});
const p={id:'test',title:'甲组',theme:'',status:'draft',publishedAt:null,revision:0,scriptVersion:'s',deckVersion:'d',algorithmVersion:'a',updatedAt:'',members:[{id:'a',name:'甲',enabled:true},{id:'b',name:'乙',enabled:true}],slides:[{id:'s0'},{id:'s1'}],sourceDeck:undefined,config:a.DEFAULT_CONFIG,overrides:{},blocks:[block('p','甲方ABC开场。','a',{spellOut:['ABC'],longPause:2,chartAction:true}),block('q','乙方发言。','b'),block('silent','附注','a',{nonspoken:true,spokenText:'保留设置'})]};
const hashes=new Map([['s0','a'.repeat(64)],['s1','b'.repeat(64)]]);
const before=await a.identifyReleaseTurns(p,hashes);
const split=a.assignSlideRange(p,1,4,1);
assert(split.blocks.length>p.blocks.length);
assert.notEqual((await a.identifyReleaseTurns(split,hashes,before))[0].fingerprint,before[0].fingerprint);
const restored=a.assignSlideRange(split,1,4,0);
assert(a.sameTurnContent(before[0],(await a.identifyReleaseTurns(restored,hashes,before))[0]));
const raw=a.paintRange(p,1,4,{actionId:'split-internal'});
assert(raw.blocks.length>p.blocks.length);
assert(a.sameTurnContent(before[0],(await a.identifyReleaseTurns(raw,hashes,before))[0]));
const spaced={...p,blocks:[block('space','  ABC def。','a',{chartAction:true,spellOut:['ABC']}),p.blocks[1]]};
const spacedBefore=await a.identifyReleaseTurns(spaced,hashes);
const blankSplit=a.paintRange(spaced,0,2,{actionId:'blank-split'});
assert(a.sameTurnContent(spacedBefore[0],(await a.identifyReleaseTurns(blankSplit,hashes,spacedBefore))[0]));
const plain={...p,blocks:[block('p','甲方ABC开场。'),p.blocks[1]]};
const pieces=a.assignScriptRange(plain,1,4,'b').blocks.map(b=>b.paragraphId==='p'?{...b,memberId:'a'}:b);
assert.equal(a.mergeFragments(pieces).length,2);
const moved=a.reconcileScript(p,'乙方发言。\r\n\r\n甲方ABC开场。\n\n附注');
assert.deepEqual(moved.blocks.map(b=>b.id),['q','p','silent']);
assert.equal(moved.blocks.at(-1).spokenText,'保留设置');
const correction=a.reconcileScript(plain,'甲方新ABC开场。\n\n乙方发言。');
assert.equal(correction.blocks[0].memberId,'a');
const two={...p,blocks:[block('p','甲方','a',{paragraphEnd:false}),block('p2','乙方','b',{paragraphId:'p'})]};
assert(a.reconcileScript(two,'甲方新增乙方').blocks.some(b=>b.text==='新增'&&b.memberId===null));
const lineSplit=a.reconcileScript(plain,'甲方ABC\n\n开场。\n\n乙方发言。');
assert.deepEqual(lineSplit.blocks.map(b=>b.memberId),['a','a','b']);
const lineJoin=a.reconcileScript(plain,'甲方ABC开场。乙方发言。');
assert.deepEqual(lineJoin.blocks.map(b=>b.memberId),['a','b']);
assert.equal(lineJoin.blocks[0].paragraphId,lineJoin.blocks[1].paragraphId);
const repeated={...plain,blocks:[block('p','相同'),block('q','相同','b')]};
assert(a.reconcileScript(repeated,'相同\n\n不同').blocks.every(b=>b.memberId===null));
assert.throws(()=>a.reconcileScript(plain,Array.from({length:501},(_,i)=>'段'+i).join('\n\n')),/500/);
const local={...plain,blocks:[{...plain.blocks[0],text:'甲改'},plain.blocks[1]]};
const remote={...plain,revision:1,blocks:[plain.blocks[0],{...plain.blocks[1],text:'乙改'}]};
assert.deepEqual(a.mergeDraft(plain,local,remote).project.blocks.map(b=>b.text),['甲改','乙改']);
assert(!a.mergeDraft(plain,local,{...local,blocks:[{...local.blocks[0],text:'甲冲突'},local.blocks[1]]}).project);
const conflict=Object.assign(new Error('CAS'),{status:409});
let server=plain,loss=true,savedIds=new Map();
const write=async(base,id,doc)=>{
 if(savedIds.has(id))return {project:savedIds.get(id)};
 if(base!==server.revision)throw conflict;
 server={...server,...doc,revision:base+1};savedIds.set(id,server);
 if(loss){loss=false;throw new TypeError('network disconnected after commit')}
 return {project:server};
};
const client=new a.DraftClient(plain,write,async()=>server,()=>{});
client.edit(local);assert.equal(await client.sync(),false);assert.equal(client.state,'offline');
const newer={...local,title:'离线继续编辑'};
client.edit(newer);
assert(await client.sync());assert.equal(savedIds.size,1);
assert(client.dirty);assert.equal(client.local.title,newer.title);
assert(await client.sync());assert.equal(client.state,'synced');
const tab=new a.DraftClient(server,write,async()=>server,()=>{});
const teammate=new a.DraftClient(server,write,async()=>server,()=>{});
tab.edit({...tab.local,title:'另一个标签页'});
teammate.edit({...teammate.local,blocks:remote.blocks});
assert(await tab.sync());assert(await teammate.sync());assert(await teammate.sync());
assert.equal(server.title,'另一个标签页');assert.equal(server.blocks[1].text,'乙改');
